export function localize(lang, key, vars = {}) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.hu;
  let str = dict[key] ?? TRANSLATIONS.hu[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replace(`{${k}}`, String(v));
  }
  return str;
}
